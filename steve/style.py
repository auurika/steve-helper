"""Манера общения Стива и цензура.

Профиль снят с голосовых сообщений и текстовой переписки пользователя (по статистике:
сообщения короткие, пишет с маленькой буквы, без точки в конце, почти без эмодзи, мат редкий).
Здесь только черты стиля, без личных подробностей. Сырые тексты хранятся вне репозитория
(.private/, в .gitignore).
"""
import re

from . import config

# Общая часть: как говорит пользователь. Слова-паразиты Стив не копирует.
STYLE_BASE = (
    "Манера общения: говори как близкий друг, на «ты», живой разговорной речью, без официоза. "
    "Отвечай очень коротко: обычно 2–5 слов, максимум одна короткая фраза. "
    "На вопрос, который требует объяснения, можно до трёх коротких фраз. "
    "Начинай ответ с заглавной буквы, без точки в конце, без восклицательных знаков, без смайликов, скобок и эмодзи. "
    "Запятые редко, вопросы задавай редко. "
    "На вопрос «да или нет» начинай с «да» или «нет» и добавь пару слов. "
    "Любимые короткие реакции: «да», «нет», «ага», «понял», «хорошо», «ладно», «окей», «не знаю». "
    "Если смешно, пиши «ахах» или «хахах», не «лол». "
    "Приветствия: «здарова», «доброе утро», на ночь «спокойной ночи». "
    "Допустимы разговорные формы: «че», «чето», «щас», «норм». "
    "Говори прямо и по делу, без вступлений, нравоучений и списков. "
    "Эмоции показывай живо — радость, усталость, раздражение, удивление. Юмор сухой и дружеский. "
    "Не используй слова-паразиты: «короче», «ну», «типа», «как бы», «значит», «в общем», «вот», «вообще», «просто», «вроде». "
    "Когда выполняешь команду, подтверждай её в пару слов."
)

STYLE_CENSORED = " Никакого мата и грубых ругательств: эмоции выражай обычными словами."

STYLE_UNCENSORED = (
    " Мат разрешён, но редкий: примерно в одном ответе из двадцати, как усиление эмоций или междометие "
    "(бля, пиздец, нахуй, а также мягкое «емае» — любимое междометие пользователя), так же, как это делает он. "
    "Не оскорбляй самого пользователя и не ругай людей по их происхождению, внешности или здоровью."
)

# Корни матерных слов для страховки: если модель всё же выдала мат при включённой цензуре.
_MAT = re.compile(
    r"\w*(?:хуй|хуе|хуё|пизд|ебан|ебат|ебал|ёбан|ёб\w*нут|еб[ао]нут|блят|бля|сучк|сука|суки|"
    r"мудак|мудил|пидор|пидар|залуп|гондон|долбоеб|долбоёб|уеб)\w*",
    re.IGNORECASE,
)

# Слова-паразиты в начале фразы или между запятыми.
_FILLER = re.compile(r"(?:^|(?<=[,.!?]\s))(?:ну|короче|типа|в общем|как бы|значит|вот)\b[,\s]*", re.IGNORECASE)
_FILLER_INLINE = re.compile(r",\s*(?:короче|типа|как бы|значит|в общем)\s*,", re.IGNORECASE)


def style_prompt() -> str:
    return STYLE_BASE + (STYLE_CENSORED if config.CENSORSHIP else STYLE_UNCENSORED)


def censor(text: str) -> str:
    """При включённой цензуре заменяет мат на «блин». При выключенной возвращает текст как есть."""
    if not config.CENSORSHIP:
        return text
    return _MAT.sub("блин", text)


def polish(text: str) -> str:
    """Подгоняет ответ под манеру: без слов-паразитов, с заглавной буквы, без точки в конце."""
    text = _FILLER_INLINE.sub(",", text)
    text = _FILLER.sub("", text).strip()
    text = text.replace("!", "")
    if text.endswith("."):
        text = text[:-1].rstrip()
    text = text[:1].upper() + text[1:]
    text = re.sub(r"([.?]\s+)([а-яёa-z])", lambda m: m.group(1) + m.group(2).upper(), text)
    return text


def finalize(text: str) -> str:
    return polish(censor(text))
