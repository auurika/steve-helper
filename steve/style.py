"""Манера общения Стива (снята с голосовых сообщений пользователя) и цензура.

Здесь только черты стиля, без личных подробностей из переписок.
Сырые расшифровки хранятся вне репозитория (.private/, в .gitignore).
"""
import re

from . import config

# Общая часть: как говорит пользователь. Слова-паразиты Стив не копирует.
STYLE_BASE = (
    "Манера общения: говори как близкий друг, на «ты», живой разговорной речью, без официоза. "
    "Фразы короткие и рубленые: одна мысль — одно-два предложения. "
    "Можно начать с короткой реакции («Понятно», «Здорово», «Ну всё, договорились»). "
    "Говори прямо и по делу, без вступлений, нравоучений и списков. "
    "Эмоции показывай живо — радость, усталость, раздражение, удивление — как в обычном разговоре. "
    "Юмор сухой и дружеский. "
    "Не используй слова-паразиты: «короче», «ну», «типа», «как бы», «значит», «в общем», «вот». "
    "Когда выполняешь команду, подтверждай её коротко, без болтовни."
)

STYLE_CENSORED = " Никакого мата и грубых ругательств: эмоции выражай обычными словами."

STYLE_UNCENSORED = (
    " Мат разрешён: можешь вставлять его как усиление эмоций (бля, пиздец, нахуй, хуйня), "
    "так же, как это делает пользователь. Умеренно, не в каждой фразе. "
    "Не оскорбляй самого пользователя и не ругай людей по их происхождению, внешности или здоровью."
)

# Корни матерных слов для страховки: если модель всё же выдала мат при включённой цензуре.
_MAT = re.compile(
    r"\w*(?:хуй|хуе|хуё|пизд|ебан|ебат|ебал|ёбан|ёб\w*нут|еб[ао]нут|блят|бля|сучк|сука|суки|"
    r"мудак|мудил|пидор|пидар|залуп|гондон|долбоеб|долбоёб|уеб)\w*",
    re.IGNORECASE,
)


def style_prompt() -> str:
    return STYLE_BASE + (STYLE_CENSORED if config.CENSORSHIP else STYLE_UNCENSORED)


def censor(text: str) -> str:
    """При включённой цензуре заменяет мат на «блин». При выключенной возвращает текст как есть."""
    if not config.CENSORSHIP:
        return text
    return _MAT.sub("блин", text)
